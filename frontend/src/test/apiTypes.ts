import { readFileSync, writeFileSync } from 'fs'
import path from 'path'
import { compile, type JSONSchema } from 'json-schema-to-typescript'

// The backend's request and response models as TypeScript types.
// backend/export_schemas.py writes their JSON Schema to src/api/schemas.json;
// this turns that into src/api/schemas.ts. `npm run api-types` runs it, and
// __tests__/apiTypes.test.ts fails while schemas.ts is out of date.
const API = path.resolve(import.meta.dirname, '../api')
export const SCHEMAS_TS = path.join(API, 'schemas.ts')

const BANNER = `// Generated by \`npm run api-types\` from schemas.json, which
// backend/export_schemas.py writes from the backend's models. Do not edit.`

export async function apiTypes() {
  const schema = JSON.parse(readFileSync(path.join(API, 'schemas.json'), 'utf8')) as JSONSchema
  const names = Object.keys((schema.$defs ?? {}) as Record<string, unknown>)
  // One property per model, so each becomes a type of its own name
  const root: JSONSchema = {
    ...schema,
    title: 'ApiSchemas',
    type: 'object',
    additionalProperties: false,
    required: names,
    properties: Object.fromEntries(names.map(name => [name, { $ref: `#/$defs/${name}` }])),
  }
  return compile(root, 'ApiSchemas', { bannerComment: BANNER, additionalProperties: false })
}

if (import.meta.main) {
  writeFileSync(SCHEMAS_TS, await apiTypes())
}
