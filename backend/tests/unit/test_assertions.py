"""Every assertion must be able to fail (CLAUDE.md, Test Architecture).

Scans every test module, and the conftest files whose fixtures and helpers
assert for the tests, for the hedges that let a test pass whatever the code
does: an assert that may not run (behind an `if`, `match` or `while`, or
inside a `try` or `suppress`), an assert that accepts several answers
(`a or b`, `x in (400, 422)`, `x if c else True`), a test that asserts nothing
at all, and a test whose every assert is one any value passes (`is not None`,
`isinstance`, a bare name).
"""
import ast
from pathlib import Path

import pytest

# Unit and integration tests alike
TESTS = Path(__file__).resolve().parents[1]

# Tests that fail by raising rather than by an assert, and why
FAIL_BY_RAISING = {
    # alembic's command.check raises AutogenerateDiffsDetected on any drift
    'test_migrations_build_the_schema_the_models_describe',
}


def _is_test(node):
    return isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith('test')


def _called_name(call):
    func = call.func
    return func.attr if isinstance(func, ast.Attribute) else getattr(func, 'id', '')


def _checks_something(test):
    """An assert, a pytest.raises/warns block, or a call to an assert_ helper"""
    for node in ast.walk(test):
        if isinstance(node, ast.Assert):
            return True
        if isinstance(node, ast.Call):
            name = _called_name(node)
            if name in {'raises', 'warns'} or name.startswith('assert_'):
                return True
    return False


def _is_weak(assert_node):
    """An assert that holds for almost anything the code could return"""
    test = assert_node.test
    if isinstance(test, ast.Name):
        return True
    if isinstance(test, ast.Call):
        return _called_name(test) == 'isinstance'
    return (isinstance(test, ast.Compare) and len(test.ops) == 1
            and isinstance(test.ops[0], ast.IsNot)
            and isinstance(test.comparators[0], ast.Constant)
            and test.comparators[0].value is None)


def _only_weak_asserts(test):
    """Asserts, all weak, and no raises block or assert_ helper beside them"""
    asserts = [node for node in ast.walk(test) if isinstance(node, ast.Assert)]
    helper_checks = [
        node for node in ast.walk(test) if isinstance(node, ast.Call)
        and (_called_name(node) in {'raises', 'warns'} or _called_name(node).startswith('assert_'))]
    return bool(asserts) and not helper_checks and all(map(_is_weak, asserts))


def _may_skip_body(node):
    """A statement whose body may not run, or whose failures it swallows"""
    if isinstance(node, (ast.If, ast.While, ast.Match, ast.Try, ast.TryStar)):
        return True
    return isinstance(node, (ast.With, ast.AsyncWith)) and any(
        isinstance(item.context_expr, ast.Call) and _called_name(item.context_expr) == 'suppress'
        for item in node.items)


def _accepts_several(test):
    """`a or b`, `x in (400, 422)` or `x if c else y`: more than one answer passes"""
    if isinstance(test, ast.BoolOp) and isinstance(test.op, ast.Or):
        return True
    if isinstance(test, ast.Compare) and any(isinstance(op, ast.In) for op in test.ops):
        return any(isinstance(c, (ast.List, ast.Tuple, ast.Set)) for c in test.comparators)
    return isinstance(test, ast.IfExp)


def _hedges(node, guarded=False):
    """(line, problem) for each hedged assert under node"""
    for child in ast.iter_child_nodes(node):
        if isinstance(child, ast.Assert):
            if guarded:
                yield child.lineno, 'assert that may not run'
            if _accepts_several(child.test):
                yield child.lineno, 'assert that accepts several answers'
        if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            # A nested helper is judged on its own
            yield from _hedges(child, False)
        else:
            yield from _hedges(child, guarded or _may_skip_body(child))


def _branches(node):
    """The if and match statements in a test, outside its nested helpers.

    A run checks one branch only, even when the assert comes after them.
    """
    for child in ast.iter_child_nodes(node):
        if isinstance(child, (ast.If, ast.Match)):
            yield child
        if not isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            yield from _branches(child)


def _violations(path, root=TESTS):
    tree = ast.parse(path.read_text(encoding='utf-8'))
    name = path.relative_to(root)
    for line, problem in _hedges(tree):
        yield f'{name}:{line}: {problem}'
    # A conftest holds fixtures and helpers, not tests: only its asserts count
    if path.name == 'conftest.py':
        return
    for test in filter(_is_test, ast.walk(tree)):
        if test.name not in FAIL_BY_RAISING and not _checks_something(test):
            yield f'{name}:{test.lineno}: {test.name} never asserts'
        if _only_weak_asserts(test):
            yield f'{name}:{test.lineno}: {test.name} has only weak asserts'
        for branch in _branches(test):
            yield f'{name}:{branch.lineno}: {test.name} branches, so a path goes unchecked'


def test_no_test_hedges_its_assertions():
    paths = sorted([*TESTS.rglob('test_*.py'), *TESTS.rglob('conftest.py')])
    violations = [v for path in paths for v in _violations(path)]

    assert violations == []


@pytest.mark.parametrize('source, expected', [
    ('def test_x(r):\n    if r.ok:\n        assert r.data == 1\n', 'may not run'),
    ('def test_x(r):\n    try:\n        assert r.data == 1\n    except Exception:\n        pass\n',
     'may not run'),
    ('def test_x(r):\n    while r.more:\n        assert r.next() == 1\n', 'may not run'),
    ('def test_x(r):\n    match r.data:\n        case 1:\n            assert r.ok\n', 'may not run'),
    ('def test_x(r):\n    with suppress(AssertionError):\n        assert r.data == 1\n', 'may not run'),
    ('def test_x(r):\n    with contextlib.suppress(AssertionError):\n        assert r.data == 1\n',
     'may not run'),
    ('def test_x(r):\n    assert r.data == 1 or r.data == 2\n', 'accepts several answers'),
    ('def test_x(r):\n    assert r.status in (400, 422)\n', 'accepts several answers'),
    ('def test_x(r):\n    assert r.status in [400, 422]\n', 'accepts several answers'),
    ('def test_x(r):\n    assert r.status in {400, 422}\n', 'accepts several answers'),
    ('def test_x(r):\n    assert r.data == 1 if r.ok else True\n', 'accepts several answers'),
    # The assert runs either way, but checks one branch's value only
    ('def test_x(r):\n    if r.naive:\n        r = r.aware\n    assert r.data == 1\n', 'branches'),
    ('def test_x(r):\n    match r.kind:\n        case 1:\n            r = r.aware\n    assert r.data == 1\n',
     'branches'),
    ('def test_x(r):\n    r.get()\n', 'test_x never asserts'),
    ('def test_x(r):\n    assert r is not None\n    assert isinstance(r, str)\n    assert r\n',
     'test_x has only weak asserts'),
])
def test_each_rule_catches_a_hedge(tmp_path, source, expected):
    """The scan itself works: a planted hedge is reported"""
    path = tmp_path / 'test_planted.py'
    path.write_text(source, encoding='utf-8')

    assert expected in ' '.join(_violations(path, tmp_path))


@pytest.mark.parametrize('source, expected', [
    ('def helper(r):\n    if r.ok:\n        assert r.data == 1\n', 'may not run'),
    ('def helper(r):\n    assert r.status in (400, 422)\n', 'accepts several answers'),
])
def test_conftest_asserts_are_checked(tmp_path, source, expected):
    """A shared helper's hedge hides in every test that calls it"""
    path = tmp_path / 'conftest.py'
    path.write_text(source, encoding='utf-8')

    assert expected in ' '.join(_violations(path, tmp_path))


def test_conftest_fixtures_are_not_tests(tmp_path):
    """A fixture named test_* asserts nothing, and need not"""
    path = tmp_path / 'conftest.py'
    path.write_text('@pytest.fixture\ndef test_user(app):\n    return app.user\n', encoding='utf-8')

    assert list(_violations(path, tmp_path)) == []


@pytest.mark.parametrize('source', [
    'def test_x(r):\n    assert r.status == 400\n',
    'def test_x(r):\n    for item in r.items:\n        assert item.ok\n',
    'def test_x(r):\n    with pytest.raises(ValueError):\n        r.get()\n',
    'def test_x(r):\n    with r.session() as s:\n        assert s.data == 1\n',
    # Membership in what the code returns pins one answer
    "def test_x(r):\n    assert 'a@b.c' in r.emails\n",
    'def test_x(self, r):\n    self.assert_failed(r.get())\n',
    # A weak assert beside a real check is fine
    'def test_x(r):\n    assert r is not None\n    assert r.status == 400\n',
    'def test_x(r):\n    assert r is not None\n    r.ping.assert_called_once()\n',
    # A helper's own if is not the test's
    'def test_x(r):\n    def helper():\n        if r:\n            return 1\n    assert helper() == 1\n',
])
def test_plain_assertions_pass(tmp_path, source):
    path = tmp_path / 'test_planted.py'
    path.write_text(source, encoding='utf-8')

    assert list(_violations(path, tmp_path)) == []
